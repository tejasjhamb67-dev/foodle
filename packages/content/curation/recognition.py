def recognition(item_id: str, fame: int, country: str) -> int:
    num = str(int(item_id[1:]))
    india = country == "India"
    for score in (5, 4, 3, 2):
        if item_id[0] == "B":
            key = f"{score}d"
        else:
            key = f"{score}i" if india else score
        if num in OVERRIDES.get(key, "").split():
            return score
    return DEFAULT_BY_FAME[fame]
